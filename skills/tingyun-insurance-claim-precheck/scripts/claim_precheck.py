# --- 工具函数 ---------------------------------------------------------------

def normalize(text):
    """把文本归一化：去除空白与常见标点，转小写。

    用于材料名称与 --materials 输入的模糊匹配。"""
    if not text:
        return ""
    drop = " \t\r\n　,，.。;；:：、/\\()（）[]【】{}<>\"'“”‘’-—_+=~`#*&%!?！？"
    buf = [ch for ch in str(text).lower() if ch not in drop]
    return "".join(buf)


def match_materials(items, provided):
    """判断每个材料项是否已被提供。

    命中规则：提供的文本中包含材料名本身，或包含该材料的任一别名。
    """
    provided_norm = [normalize(p) for p in provided if normalize(p)]
    hits = {}
    for idx, item in enumerate(items):
        candidates = [item["name"]] + list(item.get("alias", []))
        ok = False
        for cand in candidates:
            cn = normalize(cand)
            if not cn:
                continue
            for pv in provided_norm:
                if cn in pv or pv in cn:
                    ok = True
                    break
            if ok:
                break
        hits[idx] = ok
    return hits


def risk_level(rate):
    """按齐备率返回风险等级：低于 60% 为高风险，60%~85% 为中风险，高于 85% 为低风险。"""
    if rate < 60:
        return RISK_HIGH
    if rate <= 85:
        return RISK_MEDIUM
    return RISK_LOW


def build_result(scenario_key, provided):
    """核心计算：生成完整的预检结果字典。

    返回字段包括场景信息、齐备率、风险等级、缺件清单（按档位分组）、
    行动建议（按优先级排序的前 3 条）与统计信息。
    """
    scenario = SCENARIOS[scenario_key]
    items = scenario["items"]
    hits = match_materials(items, provided)

    total_weight = sum(TIER_WEIGHTS[item.get("tier", "required")] for item in items)
    got_weight = 0
    missing = {tier: [] for tier in TIER_ORDER}
    prepared = []

    for idx, item in enumerate(items):
        tier = item.get("tier", "required")
        if hits[idx]:
            got_weight += TIER_WEIGHTS[tier]
            prepared.append(item["name"])
        else:
            missing[tier].append(item)

    rate = 0.0 if total_weight == 0 else round(got_weight * 100.0 / total_weight, 1)

    # 缺件影响：必备缺件优先，其次视情况必备，加分材料仅提示
    actions = []
    for item in missing["required"]:
        actions.append({
            "priority": 1,
            "material": item["name"],
            "action": item["miss"],
            "how_to_fix": item["alt"],
        })
    for item in missing["conditional"]:
        actions.append({
            "priority": 2,
            "material": item["name"],
            "action": item["miss"],
            "how_to_fix": item["alt"],
        })
    for item in missing["bonus"]:
        actions.append({
            "priority": 3,
            "material": item["name"],
            "action": item["miss"],
            "how_to_fix": item["alt"],
        })
    actions.sort(key=lambda a: (a["priority"],))
    top_actions = actions[:3]

    return {
        "scenario": scenario_key,
        "scenario_label": scenario["label"],
        "scenario_scope": scenario["scope"],
        "materials_provided": provided,
        "materials_matched": prepared,
        "completeness_rate": rate,
        "risk_level": risk_level(rate),
        "risk_basis": "齐备率低于 60% 为高风险，60%~85% 为中风险，高于 85% 为低风险",
        "total_materials": len(items),
        "matched_count": len(prepared),
        "missing_counts": {
            "required": len(missing["required"]),
            "conditional": len(missing["conditional"]),
            "bonus": len(missing["bonus"]),
        },
        "missing": {
            tier: [
                {
                    "name": item["name"],
                    "spec": item["spec"],
                    "missing_consequence": item["miss"],
                    "alternative_path": item["alt"],
                }
                for item in missing[tier]
            ]
            for tier in TIER_ORDER
        },
        "top_actions": top_actions,
        "notes": [
            "本结果仅反映材料形式的齐备程度，不代表能否获得赔付。",
            "材料要求因保险公司、险种与保单条款而异，具体以投保合同与承保公司要求为准。",
        ],
    }


# --- 输出 -------------------------------------------------------------------

def print_text(result):
    """以可读文本输出预检结果（不使用任何 emoji，避免控制台编码问题）。"""
    out = []
    out.append("=" * 60)
    out.append("保险理赔材料预检结果")
    out.append("=" * 60)
    out.append("场景：%s（%s）" % (result["scenario_label"], result["scenario"]))
    out.append("适用范围：%s" % result["scenario_scope"])
    out.append("")
    out.append("已备材料（匹配到）：%d 项 / 共 %d 项" % (
        result["matched_count"], result["total_materials"]))
    if result["materials_matched"]:
        out.append("  - " + "；".join(result["materials_matched"]))
    out.append("齐备率：%.1f%%" % result["completeness_rate"])
    out.append("风险等级：%s" % result["risk_level"])
    out.append("说明：%s" % result["risk_basis"])
    out.append("")

    labels = TIER_LABELS
    for tier in TIER_ORDER:
        group = result["missing"][tier]
        out.append("-" * 60)
        out.append("%s缺件：%d 项" % (labels[tier], len(group)))
        out.append("-" * 60)
        if not group:
            out.append("  无")
            continue
        for item in group:
            out.append("  * %s" % item["name"])
            out.append("    规格要求：%s" % item["spec"])
            out.append("    缺了会怎样：%s" % item["missing_consequence"])
            out.append("    补齐路径：%s" % item["alternative_path"])
        out.append("")

    out.append("=" * 60)
    out.append("优先行动建议（前 3 条）")
    out.append("=" * 60)
    if not result["top_actions"]:
        out.append("  必备与视情况必备材料已准备齐全，可联系承保公司确认提交方式与时效要求。")
    for i, act in enumerate(result["top_actions"], 1):
        out.append("  %d. %s" % (i, act["material"]))
        out.append("     原因：%s" % act["action"])
        out.append("     做法：%s" % act["how_to_fix"])
    out.append("")

    out.append("提示：")
    for note in result["notes"]:
        out.append("  - " + note)
    out.append("  - 提交前请再次核对投保合同与承保公司的材料清单，二者才是最终依据。")
    print("\n".join(out))


def parse_args(argv):
    """解析命令行参数。"""
    parser = argparse.ArgumentParser(
        prog="claim_precheck.py",
        description="保险理赔材料预检助手：按场景核对材料齐备性，输出缺件清单与行动建议。",
    )
    parser.add_argument(
        "--scenario",
        choices=sorted(SCENARIOS.keys()),
        help="出险场景标识，可选：%s" % "、".join(sorted(SCENARIOS.keys())),
    )
    parser.add_argument(
        "--materials",
        default="",
        help="已备材料，逗号分隔，例如：\"身份证,出院小结,费用清单\"",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        dest="as_json",
        help="以 JSON 格式输出，便于上层程序调用",
    )
    parser.add_argument(
        "--list-scenarios",
        action="store_true",
        dest="list_scenarios",
        help="列出全部场景及其说明",
    )
    return parser.parse_args(argv)


def list_scenarios():
    """打印全部场景清单。"""
    print("可用场景：")
    for key in sorted(SCENARIOS.keys()):
        print("  %-18s %s" % (key, SCENARIOS[key]["label"]))
        print("  %-18s 适用于：%s" % ("", SCENARIOS[key]["scope"]))


def main(argv=None):
    """程序入口：解析参数 -> 计算 -> 输出。"""
    args = parse_args(argv if argv is not None else sys.argv[1:])

    if args.list_scenarios:
        list_scenarios()
        return 0

    if not args.scenario:
        print("错误：必须通过 --scenario 指定出险场景。使用 --list-scenarios 查看全部场景。")
        return 2

    provided = [m.strip() for m in args.materials.split(",") if m.strip()]
    result = build_result(args.scenario, provided)

    if args.as_json:
        print(json.dumps(result, ensure_ascii=False, indent=2))
    else:
        print_text(result)
    return 0


if __name__ == "__main__":
    sys.exit(main())
